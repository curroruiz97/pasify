/**
 * Normaliza un string para búsqueda case/accent-insensitive.
 *   "Cádiz"  → "cadiz"
 *   "L'HOSPITALET" → "l hospitalet"
 */
export const normalizeForSearch = (s: string): string =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/['`´’]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
